# Lifespan context manager
@asynccontextmanager
async def lifespan(app: FastAPI):
    """Handle startup and shutdown for auth service."""
    logger.info("🚀 AUTH SERVICE STARTUP: Initializing auth-service (port 8003)...")
    try:
        db_path = os.getenv("DATABASE_URL", "../roadwatch.db")
        db = init_database(db_path)
        logger.info(f"✓ Database initialized: {db_path}")
        app.state.db = db
    except Exception as e:
        logger.error(f"✗ Database initialization failed: {e}", exc_info=True)
        raise
    
    yield  # App runs here
    
    # Shutdown
    logger.info("🛑 AUTH SERVICE SHUTDOWN: Closing auth-service...")
    try:
        db = get_db()
        db.close()
        logger.info("✓ Database connection closed")
    except Exception as e:
        logger.warning(f"Database shutdown error: {e}")


