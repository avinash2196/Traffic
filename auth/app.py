@app.post("/api/auth/signup", tags=["Auth"], status_code=201)
async def signup(body: dict):
    """Citizen signup endpoint.
    
    Request body:
        - email: valid email address
        - full_name: citizen's full name
        - password: password (minimum 8 characters)
    
    Returns 201 Created with citizen profile (citizen_id auto-generated).
    Returns 400 Bad Request for validation errors.
    Returns 409 Conflict if email already exists.
    
    Note: citizen_id is auto-generated by system and returned in response.
    """
    try:
        email = body.get("email", "").strip()
        full_name = body.get("full_name", "").strip()
        password = body.get("password", "")
        
        # Validation
        if not email or not full_name or not password:
            return JSONResponse(
                status_code=400,
                content={"error": "Missing required fields: email, full_name, password"}
            )
        
        if not is_valid_email(email):
            return JSONResponse(
                status_code=400,
                content={"error": "Invalid email format"}
            )
        
        if not is_valid_password(password):
            return JSONResponse(
                status_code=400,
                content={"error": "Password must be at least 8 characters"}
            )
        
        # Auto-generate citizen_id
        citizen_id = f"CTZN_{uuid4().hex[:8].upper()}"
        
        # Check for email duplicates only
        db = get_db()
        cursor = db.execute(
            "SELECT id FROM citizens WHERE email = ?",
            (email,)
        )
        if cursor.fetchone():
            return JSONResponse(
                status_code=409,
                content={"error": "Email already exists"}
            )
        
        # Hash password and create citizen record
        password_hash = hash_password(password)
        now = datetime.now(timezone.utc).isoformat()
        
        db.execute(
            """INSERT INTO citizens (id, email, full_name, password_hash, created_at, is_active)
               VALUES (?, ?, ?, ?, ?, TRUE)""",
            (citizen_id, email, full_name, password_hash, now)
        )
        db.connection.commit()
        
        return JSONResponse(
            status_code=201,
            content={
                "citizen_id": citizen_id,
                "email": email,
                "full_name": full_name,
                "created_at": now
            }
        )
    
    except Exception as e:
        logger.error(f"Signup error: {e}")
        return JSONResponse(
            status_code=500,
            content={"error": "Internal server error"}
        )


@app.post("/api/auth/login", tags=["Auth"], status_code=200)
async def login(body: dict):
    """Citizen login endpoint.
    
    Request body (choose one):
        - email + password: citizen's email and password
        - citizen_id + password: citizen's ID and password
    
    Returns 200 OK with session token and citizen profile.
    Returns 401 Unauthorized for invalid credentials.
    """
    try:
        email = body.get("email", "").strip()
        citizen_id = body.get("citizen_id", "").strip()
        password = body.get("password", "")
        
        if not password:
            return JSONResponse(
                status_code=401,
                content={"error": "Invalid credentials"}
            )
        
        # Lookup citizen by email or citizen_id
        db = get_db()
        if email:
            cursor = db.execute(
                "SELECT id, email, full_name, password_hash FROM citizens WHERE email = ? AND is_active = TRUE",
                (email,)
            )
        elif citizen_id:
            cursor = db.execute(
                "SELECT id, email, full_name, password_hash FROM citizens WHERE id = ? AND is_active = TRUE",
                (citizen_id,)
            )
        else:
            return JSONResponse(
                status_code=401,
                content={"error": "Invalid credentials"}
            )
        
        row = cursor.fetchone()
        
        if not row:
            return JSONResponse(
                status_code=401,
                content={"error": "Invalid credentials"}
            )
        
        # Verify password
        password_hash = row[3]
        if not verify_password(password, password_hash):
            return JSONResponse(
                status_code=401,
                content={"error": "Invalid credentials"}
            )
        
        # Generate token and update last_login_at
        citizen_id = row[0]
        session_token = generate_session_token(citizen_id)
        now = datetime.now(timezone.utc).isoformat()
        
        db.execute(
            "UPDATE citizens SET last_login_at = ? WHERE id = ?",
            (now, citizen_id)
        )
        db.connection.commit()
        
        return JSONResponse(
            status_code=200,
            content={
                "session_token": session_token,
                "citizen_id": citizen_id,
                "email": row[1],
                "full_name": row[2]
            }
        )
    
    except Exception as e:
        logger.error(f"Login error: {e}")
        return JSONResponse(
            status_code=500,
            content={"error": "Internal server error"}
        )


@app.post("/api/auth/logout", tags=["Auth"], status_code=204)
async def logout(request: Request):
    """Citizen logout endpoint.
    
    Clears session token on server (client should clear localStorage).
    Returns 204 No Content.
    """
    try:
        citizen_id = request.scope.get("citizen_id")
        if not citizen_id:
            return JSONResponse(status_code=401, content={"error": "Not authenticated"})
        
        # For MVP with stateless JWT, nothing to clear server-side
        # Client clears localStorage
        return JSONResponse(status_code=204, content="")
    
    except Exception as e:
        logger.error(f"Logout error: {e}")
        return JSONResponse(status_code=500, content={"error": "Internal server error"})


@app.get("/api/auth/me", tags=["Auth"])
async def get_current_citizen(request: Request):
    """Get current authenticated citizen's profile.
    
    Returns 200 OK with citizen profile (no password).
    Returns 401 Unauthorized if not authenticated.
    """
    try:
        # Check bearer token
        auth_header = request.headers.get("Authorization", "")
        if auth_header.startswith("Bearer "):
            token = auth_header.split(" ", 1)[1]
            citizen_id = validate_session_token(token)
        else:
            return JSONResponse(status_code=401, content={"error": "Not authenticated"})
        
        if not citizen_id:
            return JSONResponse(status_code=401, content={"error": "Invalid or expired token"})
        
        # Lookup citizen
        db = get_db()
        cursor = db.execute(
            "SELECT id, email, full_name, created_at, last_login_at FROM citizens WHERE id = ? AND is_active = TRUE",
            (citizen_id,)
        )
        row = cursor.fetchone()
        
        if not row:
            return JSONResponse(status_code=401, content={"error": "Citizen not found"})
        
        return JSONResponse(
            status_code=200,
            content={
                "citizen_id": row[0],
                "email": row[1],
                "full_name": row[2],
                "created_at": row[3],
                "last_login_at": row[4]
            }
        )
    
    except Exception as e:
        logger.error(f"Get current citizen error: {e}")
        return JSONResponse(status_code=500, content={"error": "Internal server error"})


